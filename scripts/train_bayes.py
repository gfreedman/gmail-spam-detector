#!/usr/bin/env python3
"""
Regenerate the BAYES_TABLE block in src/Patterns.gs from the fixture corpus.

    python3 scripts/train_bayes.py            # rewrite the block, print the evaluation
    python3 scripts/train_bayes.py --check    # evaluate only, write nothing
    python3 scripts/train_bayes.py --enable   # also switch Rule 14 ON (default: keep the file's flag; shipped OFF)
    python3 scripts/train_bayes.py --holdout 2026-10-23
        # TEMPORAL holdout: train only on spam dated before the cut (plus all ham), then
        # score the spam dated on or after it. This is the acceptance test for a retrain:
        # weights are never judged on mail they were fitted to.

Why a script: a miss used to cost a hand-written rule and a release. A miss is now
DATA: add the .eml to tests/spam_examples (or real kept mail to the ham side), rerun this,
commit the regenerated block. The tokenizer and scorer are imported from the test
harness, so training, the Python mirror and the shipped JavaScript (bayesTokens /
bayesScore in Text.gs) use one definition.

Weights are POSITIVE integers (10 x the natural-log odds, smoothed, spam-leaning only), so
the Python and JS scores are bit-identical and cannot be lowered by padding. Spam = tests/spam_examples + scam_examples; ham =
tests/ham_examples. The ham is mostly synthetic: the threshold is a starting point
that exportHamScores() (Maintenance.gs, run by hand inside Gmail)
is meant to correct with the user's real kept mail.
"""
import importlib.util, io, contextlib, math, re, sys, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIN_COUNT = 3        # a token must appear in this many training documents
MIN_ABS_W = 25       # keep weights >= 2.5 nats: weak tokens only add noise and size
THRESHOLD = 550      # 55.0 nats over the top-K tokens (500 sat at ordinary long English, review r6)
TOP_K = 20
BEGIN = '// ===== BAYES TABLE (generated by scripts/train_bayes.py; do not edit by hand) BEGIN ====='
END = '// ===== BAYES TABLE END ====='


def load_harness():
    spec = importlib.util.spec_from_file_location('harness', ROOT / 'tests' / 'test_spam_detector.py')
    mod = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(mod)
    return mod


def docs(h, folder):
    out = []
    for p in sorted((ROOT / 'tests' / folder).glob('*.eml')):
        parsed = h.parse_eml(p)
        raw = p.read_text(encoding='utf-8', errors='ignore')
        lu = bool(h._raw_header(raw, 'List-Unsubscribe'))
        out.append((p.name, h._bayes_tokens(parsed.subject, parsed.body, lu)))
    return out


def train(rows):
    ns = sum(1 for _, y, _ in rows if y)
    nh = len(rows) - ns
    cs, ch = collections.Counter(), collections.Counter()
    for _, y, toks in rows:
        for t in toks:
            (cs if y else ch)[t] += 1
    table = {}
    for t in set(cs) | set(ch):
        if cs[t] + ch[t] < MIN_COUNT:
            continue
        w = round(10 * math.log(((cs[t] + .5) / (ns + 1)) / ((ch[t] + .5) / (nh + 1))))
        # POSITIVE weights only. Ham-leaning words are never stored, so appending ordinary
        # words to a spam mail cannot lower its score (a signed table lost 616 -> 317 to five
        # appended words in review). A word common in ham earns a small or zero spam weight
        # through the training counts instead.
        if w >= MIN_ABS_W:
            table[t] = int(w)
    return table


def score(table, toks):
    return sum(sorted((table[t] for t in toks if t in table), reverse=True)[:TOP_K])


def holdout(h, cut_text):
    import email.utils, datetime
    from email import policy
    cut = datetime.datetime.strptime(cut_text, '%Y-%m-%d')
    train_rows, test_rows = [], []
    for folder in ('spam_examples', 'scam_examples'):
        for p in sorted((ROOT / 'tests' / folder).glob('*.eml')):
            parsed = h.parse_eml(p)
            raw = p.read_text(encoding='utf-8', errors='ignore')
            toks = h._bayes_tokens(parsed.subject, parsed.body, bool(h._raw_header(raw, 'List-Unsubscribe')))
            msg = email.message_from_binary_file(open(p, 'rb'), policy=policy.default)
            try:
                when = email.utils.parsedate_to_datetime(str(msg.get('Date'))).replace(tzinfo=None)
            except Exception:
                print(f'  (skipped, no parseable Date: {p.name})')
                continue
            (test_rows if when >= cut else train_rows).append((p.name, 1, toks, when))
    ham = [(n, 0, t, None) for n, t in docs(h, 'ham_examples')]
    table = train([(n, y, t) for n, y, t, _ in train_rows + ham])
    print(f'train: {len(train_rows)} spam dated before {cut_text} + {len(ham)} ham; table {len(table)} tokens')
    print(f'held-out spam (dated {cut_text} or later): {len(test_rows)}')
    caught = 0
    for n, _, t, when in sorted(test_rows, key=lambda r: r[3]):
        s = score(table, t)
        caught += s >= THRESHOLD
        print(f'  {s:5d} {"CAUGHT" if s >= THRESHOLD else "missed"}  {when.date()}  {n[:52]}')
    print(f'held-out caught at {THRESHOLD}: {caught}/{len(test_rows)};  ham max (in-sample, synthetic): '
          f'{max(score(table, t) for _, _, t, _ in ham)}')


def main():
    if '--holdout' in sys.argv:
        return holdout(load_harness(), sys.argv[sys.argv.index('--holdout') + 1])
    check_only = '--check' in sys.argv
    h = load_harness()
    spam = docs(h, 'spam_examples') + docs(h, 'scam_examples')
    ham = docs(h, 'ham_examples')
    rows = [(n, 1, t) for n, t in spam] + [(n, 0, t) for n, t in ham]
    print(f'training documents: {len(spam)} spam (incl. scam), {len(ham)} ham')

    # Leave-one-out: the honest in-corpus number (the table below trains on everything).
    loo_s, loo_h = [], []
    for i, (n, y, t) in enumerate(rows):
        s = score(train(rows[:i] + rows[i + 1:]), t)
        (loo_s if y else loo_h).append(s)
    print(f'leave-one-out: spam >= {THRESHOLD}: {sum(s >= THRESHOLD for s in loo_s)}/{len(loo_s)}   '
          f'ham >= {THRESHOLD}: {sum(s >= THRESHOLD for s in loo_h)}/{len(loo_h)}   ham max {max(loo_h)}')

    table = train(rows)
    full_s = [score(table, t) for _, y, t in rows if y]
    full_h = [score(table, t) for _, y, t in rows if not y]
    print(f'in-sample (optimistic): spam >= {THRESHOLD}: {sum(s >= THRESHOLD for s in full_s)}/{len(full_s)}   '
          f'ham >= {THRESHOLD}: {sum(s >= THRESHOLD for s in full_h)}/{len(full_h)}   ham max {max(full_h)}')
    body = '\n'.join(f"  '{t}': {w}," for t, w in sorted(table.items()))
    # The enable flag is preserved from the current file unless --enable / --disable is given:
    # regenerating the table must never silently switch a quarantine rule on.
    cur = (ROOT / 'src' / 'Patterns.gs').read_text(encoding='utf-8')
    m = re.search(r'let BAYES_RULE_ENABLED = (true|false);', cur)
    enabled = m.group(1) if m else 'false'
    if '--enable' in sys.argv: enabled = 'true'
    if '--disable' in sys.argv: enabled = 'false'
    block = (f'{BEGIN}\nlet BAYES_RULE_ENABLED = {enabled};\nconst BAYES_QUARANTINE_SCORE = {THRESHOLD};\nconst BAYES_TOP_K = {TOP_K};\n'
             f'const BAYES_TABLE = Object.freeze({{\n{body}\n}});\n{END}')
    print(f'table: {len(table)} tokens, {len(block) / 1024:.1f} KB')
    if check_only:
        return
    path = ROOT / 'src' / 'Patterns.gs'
    src = path.read_text(encoding='utf-8')
    new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: block, src, flags=re.S)
    if new == src:
        print('Patterns.gs already up to date')
    path.write_text(new, encoding='utf-8')
    print('wrote', path)


if __name__ == '__main__':
    main()
